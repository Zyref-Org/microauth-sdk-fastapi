"""The SDK must parse exactly what the Go API emits.

The fixtures in ``tests/contract`` are generated by the API's
``TestSDKContractFixtures`` and copied here verbatim.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from microauth_fastapi.models import CustomerBalance
from microauth_fastapi.reporter import _parse_acknowledgements
from microauth_fastapi.sdk import _parse_snapshot

CONTRACT_DIR = Path(__file__).parent / "contract"
API_CONTRACT_DIR = (
    Path(__file__).resolve().parents[3]
    / "api"
    / "internal"
    / "modules"
    / "sdkapi"
    / "testdata"
    / "contract"
)


def load(name: str) -> dict[str, Any]:
    data = json.loads((CONTRACT_DIR / name).read_text())
    assert isinstance(data, dict)
    return data


def test_snapshot_fixture_parses_with_every_customer_status() -> None:
    snapshot = _parse_snapshot(load("snapshot.json"))

    statuses = {customer.status for customer in snapshot.customers.values()}
    assert statuses == {"active", "suspended", "billing_suspended"}
    seqs = {
        customer.status: customer.balance_seq
        for customer in snapshot.customers.values()
    }
    assert seqs == {"active": 7, "suspended": 3, "billing_suspended": 12}
    assert snapshot.billable_statuses == frozenset({200, 201})
    assert snapshot.platform_allowance is not None
    assert snapshot.platform_allowance.remaining == 996_400
    assert len(snapshot.keys) == 1


def test_snapshot_without_balance_seq_still_parses() -> None:
    legacy = load("snapshot.json")
    for customer in legacy["customers"]:
        del customer["balance_seq"]
    snapshot = _parse_snapshot(legacy)
    assert all(c.balance_seq is None for c in snapshot.customers.values())


def test_usage_fixture_maps_every_result_status() -> None:
    response = load("usage_response.json")
    ids = [result["idempotency_key"] for result in response["results"]]

    plan = _parse_acknowledgements(response, ids)

    assert plan.error is None
    assert plan.accepted == ids[:2]
    assert plan.rejected == {ids[2]: "insufficient credit balance"}
    assert plan.retry == [ids[3]]
    assert plan.balances == [
        CustomerBalance(
            customer_id="2b7c1f8e-5d34-4a9b-8c21-6e0f3d9a7b55",
            credit_balance_micro=4_997_000,
            balance_seq=8,
        )
    ]


@pytest.mark.parametrize(
    "customers",
    [
        None,
        "nope",
        [{"id": "c", "credit_balance_micro": 1}],
        [{"id": "c", "credit_balance_micro": True, "balance_seq": 1}],
        [{"id": "c", "credit_balance_micro": 1, "balance_seq": -1}],
    ],
)
def test_malformed_committed_balances_fall_back_safely(customers: Any) -> None:
    response = load("usage_response.json")
    response["customers"] = customers
    ids = [result["idempotency_key"] for result in response["results"]]
    plan = _parse_acknowledgements(response, ids)
    assert plan.error is None
    assert plan.balances == []


@pytest.mark.skipif(
    not API_CONTRACT_DIR.is_dir(),
    reason="the API repository is not checked out next to the SDK",
)
@pytest.mark.parametrize("name", ["snapshot.json", "usage_response.json"])
def test_fixtures_match_the_api_repository(name: str) -> None:
    assert (CONTRACT_DIR / name).read_bytes() == (API_CONTRACT_DIR / name).read_bytes()
